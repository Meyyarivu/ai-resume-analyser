"use client";

import { useState } from "react";
import { Download, FileText, Check, Printer } from "lucide-react";
import { AnalysisResult } from "@/types/analyzer";

interface ExportModalProps {
  data: AnalysisResult;
  isOpen: boolean;
  onClose: () => void;
}

export function ExportModal({ data, isOpen, onClose }: ExportModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdownReport = () => {
    return `# ATS Resume Audit Report
Candidate: ${data.candidateName || "Candidate"}
Target Role: ${data.targetRole || "Target Role"}
Date: ${new Date(data.analyzedAt).toLocaleDateString()}

---

## 1. Executive Scores
- ATS Compatibility Score: ${data.atsCompatibilityScore}/100
- Skill Match: ${data.skillMatchPercentage}%
- Experience Relevance: ${data.experienceRelevanceScore}/100
- Overall Weighted Score: ${data.overallScore}/100

### Section Breakdown
- Impact & Measurable Metrics: ${data.sectionScores.impactAndMetrics}/100
- Formatting & Structure: ${data.sectionScores.formattingAndClarity}/100
- Keyword Optimization: ${data.sectionScores.keywordOptimization}/100
- Brevity & Seniority Alignment: ${data.sectionScores.brevityAndRelevance}/100

---

## 2. Executive Summary
${data.resumeSummary}

---

## 3. ATS Keyword Analysis
### Matched Keywords (${data.matchedKeywords.length})
${data.matchedKeywords.map((k) => `- ${k}`).join("\n")}

### Missing / Underrepresented Keywords (${data.missingKeywords.length})
${data.missingKeywords
  .map((k) => `- **${k.keyword}** [${k.importance.toUpperCase()} PRIORITY]: ${k.context}`)
  .join("\n")}

---

## 4. Prioritized Actionable Improvements
${data.actionableSuggestions
  .map(
    (a, i) =>
      `### ${i + 1}. [${a.category}] - ${a.impact.toUpperCase()} IMPACT
${a.suggestion}
${
  a.exampleBeforeAfter
    ? `> **Original:** ${a.exampleBeforeAfter.before}\n> **Optimized:** ${a.exampleBeforeAfter.after}`
    : ""
}`
  )
  .join("\n\n")}

---

## 5. Optimized Professional Summary
**Critique:** ${data.professionalSummaryReview.currentAssessment}

**Optimized Version:**
"${data.professionalSummaryReview.improvedVersion}"

---

## 6. Strengths & Opportunities
### Strengths:
${data.strengths.map((s) => `- ${s}`).join("\n")}

### Areas for Improvement:
${data.weaknesses.map((w) => `- ${w}`).join("\n")}

---
*Generated by ATS Pulse AI Resume Analyzer using Groq Llama 3.3. ATS scores are indicative estimations.*
`;
  };

  const handleDownload = () => {
    const report = generateMarkdownReport();
    const blob = new Blob([report], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `ATS-Resume-Audit-${(data.candidateName || "Candidate").replace(/\s+/g, "-")}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdownReport());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-sm">
      <div className="w-full max-w-lg rounded-2xl border border-neutral-200 bg-white p-6 shadow-2xl dark:border-neutral-800 dark:bg-neutral-900">
        <div className="flex items-center justify-between pb-3">
          <div className="flex items-center gap-2">
            <div className="rounded-lg bg-indigo-50 p-2 dark:bg-indigo-950/60">
              <Download className="h-5 w-5 text-indigo-600 dark:text-indigo-400" />
            </div>
            <div>
              <h3 className="font-semibold text-neutral-900 dark:text-white">
                Export ATS Audit Report
              </h3>
              <p className="text-xs text-neutral-500">
                Save your complete audit and tailored recommendations.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="text-neutral-400 hover:text-neutral-600 dark:hover:text-neutral-200"
          >
            ✕
          </button>
        </div>

        <div className="mt-4 space-y-3">
          <button
            onClick={handleDownload}
            className="flex w-full items-center justify-between rounded-xl border border-neutral-200 p-3.5 text-left transition hover:bg-neutral-50 dark:border-neutral-800 dark:hover:bg-neutral-800"
          >
            <div className="flex items-center gap-3">
              <FileText className="h-5 w-5 text-indigo-600 dark:text-indigo-400" />
              <div>
                <p className="text-xs font-semibold text-neutral-900 dark:text-white">
                  Download Markdown (.md)
                </p>
                <p className="text-[11px] text-neutral-500">
                  Full text report formatted in clean GitHub markdown
                </p>
              </div>
            </div>
            <Download className="h-4 w-4 text-neutral-400" />
          </button>

          <button
            onClick={handleCopyMarkdown}
            className="flex w-full items-center justify-between rounded-xl border border-neutral-200 p-3.5 text-left transition hover:bg-neutral-50 dark:border-neutral-800 dark:hover:bg-neutral-800"
          >
            <div className="flex items-center gap-3">
              <Check className="h-5 w-5 text-emerald-600 dark:text-emerald-400" />
              <div>
                <p className="text-xs font-semibold text-neutral-900 dark:text-white">
                  Copy to Clipboard
                </p>
                <p className="text-[11px] text-neutral-500">
                  {copied ? "Copied to clipboard!" : "Copy formatted report into your notes"}
                </p>
              </div>
            </div>
            {copied && <span className="text-xs font-semibold text-emerald-600">Copied!</span>}
          </button>

          <button
            onClick={handlePrint}
            className="flex w-full items-center justify-between rounded-xl border border-neutral-200 p-3.5 text-left transition hover:bg-neutral-50 dark:border-neutral-800 dark:hover:bg-neutral-800"
          >
            <div className="flex items-center gap-3">
              <Printer className="h-5 w-5 text-blue-600 dark:text-blue-400" />
              <div>
                <p className="text-xs font-semibold text-neutral-900 dark:text-white">
                  Print / Save as PDF
                </p>
                <p className="text-[11px] text-neutral-500">
                  Open browser print dialog to export a formatted PDF document
                </p>
              </div>
            </div>
            <Printer className="h-4 w-4 text-neutral-400" />
          </button>
        </div>

        <div className="mt-6 flex justify-end">
          <button
            onClick={onClose}
            className="rounded-lg px-4 py-2 text-xs font-medium text-neutral-600 hover:bg-neutral-100 dark:text-neutral-400 dark:hover:bg-neutral-800"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
