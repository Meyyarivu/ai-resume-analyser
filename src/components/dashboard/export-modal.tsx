"use client";

import { useEffect, useRef, useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { Download, FileText, Check, Printer, X } from "lucide-react";
import { AnalysisResult } from "@/types/analyzer";

interface ExportModalProps {
  data: AnalysisResult;
  isOpen: boolean;
  onClose: () => void;
}

export function ExportModal({ data, isOpen, onClose }: ExportModalProps) {
  const [copied, setCopied] = useState(false);
  const dialogRef = useRef<HTMLDivElement>(null);
  const closeButtonRef = useRef<HTMLButtonElement>(null);
  const wasOpenRef = useRef(false);
  const onCloseRef = useRef(onClose);

  useEffect(() => { onCloseRef.current = onClose; }, [onClose]);

  useEffect(() => {
    if (!isOpen) {
      if (wasOpenRef.current) document.getElementById("export-report-trigger")?.focus();
      wasOpenRef.current = false;
      return;
    }
    wasOpenRef.current = true;
    closeButtonRef.current?.focus();
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") onCloseRef.current();
      if (event.key === "Tab" && dialogRef.current) {
        const nodes = dialogRef.current.querySelectorAll<HTMLElement>('button:not([disabled])');
        const first = nodes[0];
        const last = nodes[nodes.length - 1];
        if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last?.focus(); }
        else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first?.focus(); }
      }
    };
    window.addEventListener("keydown", onKeyDown);
    return () => window.removeEventListener("keydown", onKeyDown);
  }, [isOpen]);

  const generateMarkdownReport = () => {
    return `# ATS Resume Audit Report
Candidate: ${data.candidateName || "Candidate"}
Target Role: ${data.targetRole || "Target Role"}
Date: ${new Date(data.analyzedAt).toLocaleDateString()}

---

## 1. Executive Scores
- Estimated ATS Compatibility: ${data.atsCompatibilityScore}/100
- Skill Match: ${data.skillMatchPercentage}%
- Experience Relevance: ${data.experienceRelevanceScore}/100
- Overall Weighted Score: ${data.overallScore}/100

### Section Breakdown
- Impact & Measurable Metrics: ${data.sectionScores.impactAndMetrics}/100
- Formatting & Structure: ${data.sectionScores.formattingAndClarity}/100
- Keyword Optimization: ${data.sectionScores.keywordOptimization}/100
- Brevity & Seniority Alignment: ${data.sectionScores.brevityAndRelevance}/100

---

## 2. Executive Summary
${data.resumeSummary}

---

## 3. ATS Keyword Analysis
### Matched Keywords (${data.matchedKeywords.length})
${data.matchedKeywords.map((k) => `- ${k}`).join("\n")}

### Missing / Underrepresented Keywords (${data.missingKeywords.length})
${data.missingKeywords
  .map((k) => `- **${k.keyword}** [${k.importance.toUpperCase()} PRIORITY]: ${k.context}`)
  .join("\n")}

---

## 4. Prioritized Actionable Improvements
${data.actionableSuggestions
  .map(
    (a, i) =>
      `### ${i + 1}. [${a.category}] - ${a.impact.toUpperCase()} IMPACT
${a.suggestion}
${
  a.exampleBeforeAfter
    ? `> **Original:** ${a.exampleBeforeAfter.before}\n> **Optimized:** ${a.exampleBeforeAfter.after}`
    : ""
}`
  )
  .join("\n\n")}

---

## 5. Optimized Professional Summary
**Critique:** ${data.professionalSummaryReview.currentAssessment}

**Optimized Version:**
"${data.professionalSummaryReview.improvedVersion}"

---

## 6. Strengths & Opportunities
### Strengths:
${data.strengths.map((s) => `- ${s}`).join("\n")}

### Areas for Improvement:
${data.weaknesses.map((w) => `- ${w}`).join("\n")}

---
*Generated by ATS Pulse AI Resume Analyzer. Scores are indicative estimates.*
`;
  };

  const handleDownload = () => {
    const report = generateMarkdownReport();
    const blob = new Blob([report], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `ATS-Resume-Audit-${(data.candidateName || "Candidate").replace(/\s+/g, "-")}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyMarkdown = () => {
    void navigator.clipboard.writeText(generateMarkdownReport()).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }).catch(() => setCopied(false));
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <AnimatePresence>
    {isOpen && <motion.div className="fixed inset-0 z-50 flex items-center justify-center bg-neutral-950/35 p-4 backdrop-blur-sm" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onMouseDown={(event) => { if (event.target === event.currentTarget) onClose(); }}>
      <motion.div ref={dialogRef} role="dialog" aria-modal="true" aria-labelledby="export-dialog-title" className="w-full max-w-lg rounded-[22px] border border-neutral-200 bg-white p-5 shadow-[0_18px_48px_rgba(0,0,0,.14)] sm:p-6" initial={{ opacity: 0, y: 10, scale: .99 }} animate={{ opacity: 1, y: 0, scale: 1 }} exit={{ opacity: 0, y: 6, scale: .99 }} transition={{ duration: .2, ease: [.2, .8, .2, 1] }}>
        <div className="flex items-center justify-between pb-3">
          <div className="flex items-center gap-2">
            <div className="rounded-lg bg-indigo-50 p-2 dark:bg-indigo-950/60">
              <Download className="h-5 w-5 text-indigo-600 dark:text-indigo-400" />
            </div>
            <div>
              <h2 id="export-dialog-title" className="font-semibold text-neutral-900">
                Export ATS Audit Report
              </h2>
              <p className="text-xs text-neutral-500">
                Save your complete audit and tailored recommendations.
              </p>
            </div>
          </div>
          <button ref={closeButtonRef}
            onClick={onClose}
            aria-label="Close export dialog"
            className="flex h-10 w-10 items-center justify-center rounded-lg text-neutral-500 hover:bg-neutral-100 hover:text-neutral-900"
          >
            <X className="h-4 w-4" aria-hidden="true" />
          </button>
        </div>

        <div className="mt-4 space-y-3">
          <button
            onClick={handleDownload}
            className="flex min-h-[68px] w-full items-center justify-between rounded-xl border border-neutral-200 p-3.5 text-left transition hover:bg-neutral-50"
          >
            <div className="flex items-center gap-3">
              <FileText className="h-5 w-5 text-indigo-600 dark:text-indigo-400" />
              <div>
                <p className="text-xs font-semibold text-neutral-900 dark:text-white">
                  Download Markdown (.md)
                </p>
                <p className="text-[11px] text-neutral-500">
                  Full text report formatted in clean GitHub markdown
                </p>
              </div>
            </div>
            <Download className="h-4 w-4 text-neutral-400" />
          </button>

          <button
            onClick={handleCopyMarkdown}
            className="flex min-h-[68px] w-full items-center justify-between rounded-xl border border-neutral-200 p-3.5 text-left transition hover:bg-neutral-50"
          >
            <div className="flex items-center gap-3">
              <Check className="h-5 w-5 text-emerald-600 dark:text-emerald-400" />
              <div>
                <p className="text-xs font-semibold text-neutral-900 dark:text-white">
                  Copy to Clipboard
                </p>
                <p className="text-[11px] text-neutral-500">
                  {copied ? "Copied to clipboard!" : "Copy formatted report into your notes"}
                </p>
              </div>
            </div>
            {copied && <span className="text-xs font-semibold text-emerald-600">Copied!</span>}
          </button>

          <button
            onClick={handlePrint}
            className="flex min-h-[68px] w-full items-center justify-between rounded-xl border border-neutral-200 p-3.5 text-left transition hover:bg-neutral-50"
          >
            <div className="flex items-center gap-3">
              <Printer className="h-5 w-5 text-blue-600 dark:text-blue-400" />
              <div>
                <p className="text-xs font-semibold text-neutral-900 dark:text-white">
                  Print / Save as PDF
                </p>
                <p aria-live="polite" className="text-[11px] text-neutral-500">
                  Open browser print dialog to export a formatted PDF document
                </p>
              </div>
            </div>
            <Printer className="h-4 w-4 text-neutral-400" />
          </button>
        </div>

        <div className="mt-6 flex justify-end">
          <button
            onClick={onClose}
            className="min-h-11 rounded-lg px-4 text-sm font-medium text-neutral-600 hover:bg-neutral-100"
          >
            Close
          </button>
        </div>
      </motion.div>
    </motion.div>}
    </AnimatePresence>
  );
}
